// =========================
// Render cards
// =========================

function renderNotes(noteList) {

    const highSchoolContainer =
        document.getElementById("highSchoolNotes");

    const universityContainer =
        document.getElementById("universityNotes");

    highSchoolContainer.innerHTML = "";
    universityContainer.innerHTML = "";

    let highSchoolCount = 0;
    let universityCount = 0;


    noteList.forEach(note => {

        const card = createCard(note);

        if (note.level === "High School") {

            highSchoolContainer.appendChild(card);

            highSchoolCount++;

        } else {

            universityContainer.appendChild(card);

            universityCount++;
        }

    });


    document.getElementById("noResults").style.display =
        noteList.length === 0
            ? "block"
            : "none";
}


// =========================
// Create card
// =========================

function createCard(note) {

    const card = document.createElement("article");

    card.className = "notebook-card";

    card.innerHTML = `

        <div class="card-icon">
            ${note.level === "High School" ? "📕" : "📘"}
        </div>

        <div class="card-meta">

            ${
                note.code
                    ? `<span class="tag">${note.code}</span>`
                    : ""
            }

            ${
                note.year
                    ? `<span class="tag">${note.year}</span>`
                    : ""
            }

        </div>

        <h3 class="card-title">
            ${note.title}
        </h3>

        <p class="card-subtitle">
            ${note.subject}
        </p>

        <div
            class="card-button"
            onclick="openPDF('${note.file}', '${escapeQuotes(note.title)}')"
        >
            Open notebook →
        </div>
    `;

    return card;
}


// =========================
// PDF viewer
// =========================

function openPDF(file, title) {

    const modal =
        document.getElementById("pdfModal");

    const viewer =
        document.getElementById("pdfViewer");

    const titleElement =
        document.getElementById("pdfTitle");

    viewer.src = file;

    titleElement.textContent = title;

    modal.classList.add("active");

    modal.setAttribute("aria-hidden", "false");

    document.body.style.overflow = "hidden";
}


function closePDF() {

    const modal =
        document.getElementById("pdfModal");

    const viewer =
        document.getElementById("pdfViewer");

    modal.classList.remove("active");

    modal.setAttribute("aria-hidden", "true");

    viewer.src = "";

    document.body.style.overflow = "";
}


// =========================
// Search
// =========================

document
    .getElementById("searchInput")
    .addEventListener("input", function () {

        const query =
            this.value
                .toLowerCase()
                .trim();

        const filtered =
            notes.filter(note => {

                return (
                    note.title.toLowerCase().includes(query) ||
                    note.subject.toLowerCase().includes(query) ||
                    note.code.toLowerCase().includes(query) ||
                    note.year.toLowerCase().includes(query)
                );

            });

        renderNotes(filtered);
    });


// =========================
// Close modal
// =========================

document
    .getElementById("closeModal")
    .addEventListener("click", closePDF);


document
    .getElementById("pdfModal")
    .addEventListener("click", function (event) {

        if (event.target === this) {
            closePDF();
        }

    });


document
    .addEventListener("keydown", function (event) {

        if (event.key === "Escape") {
            closePDF();
        }

    });


// =========================
// Statistics
