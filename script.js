document.getElementById("totalNotes")
    .textContent = notes.length;

document.getElementById("totalSubjects")
    .textContent =
        new Set(notes.map(note => note.subject)).size;


// =========================
// Utility
// =========================

function escapeQuotes(string) {

    return string
        .replace(/'/g, "\\'")
        .replace(/"/g, "&quot;");
}


// =========================
// Initial render
// =========================

renderNotes(notes);